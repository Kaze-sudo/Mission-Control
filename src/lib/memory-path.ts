/**
 * Shared path safety helpers for memory filesystem routes.
 * Extracted from /api/memory/route.ts so all memory routes use the same
 * path traversal protection and prefix allowlist enforcement.
 */

import { lstat, realpath } from 'fs/promises'
import { dirname, sep } from 'path'
import { config } from '@/lib/config'
import { resolveWithin } from '@/lib/paths'

export const MEMORY_PATH = config.memoryDir
export const MEMORY_ALLOWED_PREFIXES = (config.memoryAllowedPrefixes || []).map((p) => p.replace(/\\/g, '/'))

export function canonicalizeMemoryRelativePath(value: unknown): string {
  const input = typeof value === 'string' ? value : ''
  if (!input || input.length > 1024 || input.includes('\0')) {
    throw new Error('Invalid memory path')
  }

  const normalized = input.replace(/\\/g, '/')
  if (normalized.startsWith('/') || /^[A-Za-z]:/.test(normalized)) {
    throw new Error('Memory path must be relative')
  }

  const segments = normalized.split('/')
  // Windows Trailing Dot rule: Win32 path normalization strips trailing dots
  // and spaces from each segment (NTFS never stores them), so a stored segment
  // like '.. ' (dot-dot-space) resolves as '..' at the filesystem boundary —
  // i.e. a traversal out of the root. On win32, path.resolve() re-bases the
  // result onto the drive root instead of throwing (POSIX returns base + '/.. '
  // which still startsWith base and fails closed), so any consumer that runs
  // Node's win32 path module (or the Windows filesystem itself) would accept a
  // segment the oracle rightly treats as outside the base. Canonical paths
  // generated by this module never end in a dot, so rejecting trailing-dot
  // segments as non-canonical is a safe strictness increase.
  if (
    segments.some(
      (segment) => !segment || segment === '.' || segment === '..' || segment.endsWith('.'),
    )
  ) {
    throw new Error('Memory path must be canonical')
  }
  return segments.join('/')
}

export function isPathAllowed(relativePath: string): boolean {
  let normalized: string
  try {
    normalized = canonicalizeMemoryRelativePath(relativePath)
  } catch {
    return false
  }
  if (!MEMORY_ALLOWED_PREFIXES.length) return true
  return MEMORY_ALLOWED_PREFIXES.some((prefix) => {
    const root = prefix.endsWith('/') ? prefix.slice(0, -1) : prefix
    return normalized === root || normalized.startsWith(`${root}/`)
  })
}

function isWithinBase(base: string, candidate: string): boolean {
  if (candidate === base) return true
  return candidate.startsWith(base + sep)
}

export async function resolveSafeMemoryPath(baseDir: string, relativePath: string): Promise<string> {
  const canonicalPath = canonicalizeMemoryRelativePath(relativePath)
  const baseReal = await realpath(baseDir)
  const fullPath = resolveWithin(baseDir, canonicalPath)

  // For non-existent targets, validate containment using the nearest existing ancestor.
  // This allows nested creates (mkdir -p) while still blocking symlink escapes.
  let current = dirname(fullPath)
  let parentReal = ''
  while (!parentReal) {
    try {
      parentReal = await realpath(current)
    } catch (err) {
      const code = (err as NodeJS.ErrnoException).code
      if (code !== 'ENOENT') throw err
      const next = dirname(current)
      if (next === current) {
        throw new Error('Parent directory not found')
      }
      current = next
    }
  }
  if (!isWithinBase(baseReal, parentReal)) {
    throw new Error('Path escapes base directory (symlink)')
  }

  // If the file exists, ensure it also resolves within base and is not a symlink.
  try {
    const st = await lstat(fullPath)
    if (st.isSymbolicLink()) {
      throw new Error('Symbolic links are not allowed')
    }
    const fileReal = await realpath(fullPath)
    if (!isWithinBase(baseReal, fileReal)) {
      throw new Error('Path escapes base directory (symlink)')
    }
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code
    if (code !== 'ENOENT') {
      throw err
    }
  }

  return fullPath
}
